-- The fee a care seeker pays once a visit is completed, and every payment attempt made for it.
ALTER TABLE bookings ADD COLUMN fee_amount NUMERIC(10,2);
ALTER TABLE bookings ADD COLUMN fee_requested_at TIMESTAMP WITH TIME ZONE;

CREATE TABLE payments (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id         BIGINT        NOT NULL REFERENCES bookings (id) ON DELETE CASCADE,
    order_id           VARCHAR(40)   NOT NULL UNIQUE,   -- what PayHere calls the payment; we make a new one for every attempt
    amount             NUMERIC(10,2) NOT NULL,
    currency           VARCHAR(3)    NOT NULL,
    status             VARCHAR(12)   NOT NULL,
    source             VARCHAR(10)   NOT NULL,          -- PAYHERE, or MANUAL when the admin recorded a payment made outside PayHere
    method             VARCHAR(20),
    payhere_payment_id VARCHAR(40),
    status_code        INTEGER,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    paid_at            TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_payments_booking ON payments (booking_id);
