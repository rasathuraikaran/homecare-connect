-- A caregiver is shown to care seekers only after an admin approved the documents their job requires.
ALTER TABLE caregiver_profiles ADD COLUMN verified BOOLEAN NOT NULL DEFAULT FALSE;

-- One current file per document type. revision goes up on every re-upload, so an admin can never approve a file they did not see.
CREATE TABLE caregiver_documents (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT      NOT NULL REFERENCES caregiver_profiles (user_id) ON DELETE CASCADE,
    doc_type      VARCHAR(30) NOT NULL,
    file_name     VARCHAR(80) NOT NULL,
    status        VARCHAR(10) NOT NULL,
    revision      INTEGER     NOT NULL DEFAULT 1,
    reject_reason VARCHAR(300),
    reviewed_by   BIGINT      REFERENCES users (id) ON DELETE SET NULL,
    reviewed_at   TIMESTAMP WITH TIME ZONE,
    uploaded_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_caregiver_document UNIQUE (user_id, doc_type)
);
CREATE INDEX idx_caregiver_documents_status ON caregiver_documents (status, uploaded_at);
