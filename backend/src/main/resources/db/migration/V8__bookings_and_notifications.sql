-- Admins are normal accounts with a flag; the flag can only be set in the database (see make-admin in start-service.sh)
ALTER TABLE users ADD COLUMN is_admin BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE bookings (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seeker_id     BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    caregiver_id  BIGINT        NOT NULL REFERENCES caregiver_profiles (user_id) ON DELETE CASCADE,
    status        VARCHAR(20)   NOT NULL,
    seeker_phone  VARCHAR(30)   NOT NULL,
    rate_type     VARCHAR(20),
    quoted_amount NUMERIC(10,2),
    note          VARCHAR(500),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_bookings_seeker ON bookings (seeker_id, created_at DESC);
CREATE INDEX idx_bookings_status ON bookings (status, created_at DESC);

-- Outbox: a row is written in the same transaction as the booking, and sent afterwards,
-- so a booking is never lost when WhatsApp is slow or down.
CREATE TABLE notifications (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id      BIGINT REFERENCES bookings (id) ON DELETE CASCADE,
    channel         VARCHAR(20)  NOT NULL,
    recipient       VARCHAR(40)  NOT NULL,
    template        VARCHAR(80)  NOT NULL,
    language        VARCHAR(10)  NOT NULL,
    params          VARCHAR(1000) NOT NULL,
    status          VARCHAR(12)  NOT NULL,
    attempts        INTEGER      NOT NULL DEFAULT 0,
    last_error      VARCHAR(500),
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    sent_at         TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_notifications_due ON notifications (status, next_attempt_at);
CREATE INDEX idx_notifications_booking ON notifications (booking_id);
