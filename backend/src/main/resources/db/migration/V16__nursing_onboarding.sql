-- Role-specific onboarding details for NURSING only.
-- Caretaker uses caretaker_onboarding (V15); Physiotherapist may have its own table later.
CREATE TABLE nursing_onboarding (
    user_id                       BIGINT PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    dob                           VARCHAR(20),
    gender                        VARCHAR(30),
    preferred_language            VARCHAR(40),
    spoken_languages              VARCHAR(255),
    emergency_contact_name        VARCHAR(150),
    emergency_contact_relation    VARCHAR(80),
    emergency_contact_phone       VARCHAR(30),
    nursing_qualification_type    VARCHAR(100),
    training_institute            VARCHAR(160),
    graduation_year               VARCHAR(10),
    registration_body             VARCHAR(80),
    registration_number           VARCHAR(80),
    registration_valid_until      VARCHAR(20),
    clinical_areas                VARCHAR(300),
    is_new_home_nurse             BOOLEAN NOT NULL DEFAULT FALSE,
    current_work_status           VARCHAR(80),
    reference_name                VARCHAR(150),
    reference_phone               VARCHAR(30),
    offers_long_duration_care     BOOLEAN NOT NULL DEFAULT FALSE,
    additional_training           VARCHAR(300),
    available_days                VARCHAR(100),
    preferred_shift               VARCHAR(80),
    min_visit_fee                 NUMERIC(10, 2),
    max_travel_distance           VARCHAR(40),
    charges_extra_for_travel      BOOLEAN NOT NULL DEFAULT FALSE,
    travel_allowance              VARCHAR(100),
    available_for_urgent          BOOLEAN NOT NULL DEFAULT TRUE,
    provides_night_services       BOOLEAN NOT NULL DEFAULT FALSE,
    night_extra_charge            VARCHAR(100),
    multiple_services_per_visit   BOOLEAN NOT NULL DEFAULT TRUE,
    provides_medical_consumables  BOOLEAN NOT NULL DEFAULT FALSE,
    available_for_recurring       BOOLEAN NOT NULL DEFAULT TRUE,
    preferred_locations           VARCHAR(200),
    call_whatsapp_phone           VARCHAR(30),
    call_method                   VARCHAR(60),
    call_available_times          VARCHAR(300),
    call_notes                    VARCHAR(200),
    consent_accurate_info         BOOLEAN NOT NULL DEFAULT FALSE,
    consent_clinical_scope        BOOLEAN NOT NULL DEFAULT FALSE,
    consent_background_check      BOOLEAN NOT NULL DEFAULT FALSE,
    consent_terms_privacy         BOOLEAN NOT NULL DEFAULT FALSE,
    consented                     BOOLEAN NOT NULL DEFAULT FALSE,
    credentials_step_saved        BOOLEAN NOT NULL DEFAULT FALSE,
    experience_step_saved         BOOLEAN NOT NULL DEFAULT FALSE,
    services_step_saved           BOOLEAN NOT NULL DEFAULT FALSE,
    identity_step_saved           BOOLEAN NOT NULL DEFAULT FALSE,
    certificates_reviewed         BOOLEAN NOT NULL DEFAULT FALSE,
    availability_step_saved       BOOLEAN NOT NULL DEFAULT FALSE,
    interview_scheduled           BOOLEAN NOT NULL DEFAULT FALSE,
    application_submitted         BOOLEAN NOT NULL DEFAULT FALSE,
    last_step                     VARCHAR(40),
    updated_at                    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE nursing_service_rates (
    user_id              BIGINT         NOT NULL REFERENCES nursing_onboarding (user_id) ON DELETE CASCADE,
    service_order        INTEGER        NOT NULL,
    service_code         VARCHAR(80)    NOT NULL,
    service_name         VARCHAR(120)   NOT NULL,
    category             VARCHAR(80),
    expected_rate        NUMERIC(10, 2) NOT NULL,
    duration_minutes     VARCHAR(40),
    experience_level     VARCHAR(80),
    times_performed      VARCHAR(40),
    last_performed       VARCHAR(60),
    brings_equipment     BOOLEAN        NOT NULL DEFAULT FALSE,
    provides_consumables BOOLEAN        NOT NULL DEFAULT FALSE,
    PRIMARY KEY (user_id, service_order)
);

CREATE TABLE nursing_work_history (
    user_id          BIGINT  NOT NULL REFERENCES nursing_onboarding (user_id) ON DELETE CASCADE,
    entry_order      INTEGER NOT NULL,
    organisation     VARCHAR(150),
    job_title        VARCHAR(120),
    department       VARCHAR(100),
    duration         VARCHAR(100),
    responsibilities VARCHAR(255),
    PRIMARY KEY (user_id, entry_order)
);
