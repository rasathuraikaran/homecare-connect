CREATE TABLE reviews (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caregiver_id BIGINT  NOT NULL REFERENCES caregiver_profiles (user_id) ON DELETE CASCADE,
    reviewer_id  BIGINT  NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    rating       INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment      VARCHAR(1000),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_review_per_pair UNIQUE (caregiver_id, reviewer_id)
);
CREATE INDEX idx_reviews_caregiver ON reviews (caregiver_id, updated_at DESC);
