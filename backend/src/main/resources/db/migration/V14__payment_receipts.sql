-- Proof of a bank transfer: the screenshot or PDF a care seeker sends after paying. The file lives on disk (uploads/receipts), only its name is kept here.
CREATE TABLE payment_receipts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id  BIGINT        NOT NULL REFERENCES bookings (id) ON DELETE CASCADE,
    file_name   VARCHAR(80)   NOT NULL,
    note        VARCHAR(300),
    uploaded_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_payment_receipts_booking ON payment_receipts (booking_id);
